    private function mailBuilder(\stdClass $state, string $kind): TransportBuilder
    {
        $message = [];
        $builder = $this->createMock(TransportBuilder::class);
        foreach (['setTemplateIdentifier' => 'template', 'setTemplateOptions' => 'options',
            'setTemplateVars' => 'variables', 'addTo' => 'recipient', 'setReplyTo' => 'reply_to'] as $method => $field) {
            $builder->method($method)->willReturnCallback(static function ($value) use (&$message, $field, $builder) {
                $message[$field] = $value;
                return $builder;
            });
        }
        $builder->method('setFromByScope')->willReturnCallback(static function ($sender, $scope) use (&$message, $builder) {
            $message['sender'] = $sender;
            $message['store_id'] = $scope;
            return $builder;
        });
        $transport = $this->createMock(TransportInterface::class);
        $transport->method('sendMessage')->willReturnCallback(static function () use ($state, $kind, &$message): void {
            self::assertNotEmpty($state->rows, 'Persistence must precede transport handoff.');
            $state->events[] = $kind . '_send';
            $state->mail[$kind][] = $message;
            if ($state->{$kind === 'admin' ? 'failAdminTransport' : 'failCustomerTransport'}) {
                throw new \RuntimeException('SMTP password boundary@example.invalid');
            }
        });
        $builder->method('getTransport')->willReturn($transport);
        return $builder;
    }

    private function dispatch(array $fixture, array $post, ?string $capture = null): array
    {
        $state = $fixture['state'];
        $state->currentPost = $post;
        $state->responseStatus = 200;
        $state->responseBody = null;
        $state->headers = [];
        $fixture['controller']->execute();
        $response = ['http_status' => $state->responseStatus,
            'body' => json_decode(json_encode($state->responseBody, JSON_THROW_ON_ERROR), true, 32, JSON_THROW_ON_ERROR)];
        self::assertSame('no-store, no-cache, must-revalidate', $state->headers['Cache-Control']);
        if ($capture !== null) {
            self::$capturedResponses[$capture] = ['id' => $capture] + $response;
            if (getenv('CORESH_CAPTURE_SUBMIT_RESPONSES') === false) {
                $recorded = json_decode((string) file_get_contents(__DIR__ . '/../Fixtures/frontend-submit-responses.json'), true, 32, JSON_THROW_ON_ERROR);
                $matching = array_values(array_filter($recorded['responses'], static fn (array $item): bool => $item['id'] === $capture));
                self::assertCount(1, $matching, 'The Node round-trip must use the captured actual controller response.');
                self::assertSame(self::$capturedResponses[$capture], $matching[0]);
            }
        }
        return $response;
    }

    private function assertSafeFailure(array $fixture, array $response, int $status): void
    {
        self::assertSame($status, $response['http_status']);
        self::assertFalse($response['body']['success']);
        self::assertArrayNotHasKey('request_id', $response['body']);
        $serialized = json_encode([$response, $fixture['state']->logs], JSON_THROW_ON_ERROR);
        foreach (['boundary@example.invalid', 'password', 'SQL', 'SMTP'] as $secret) {
            self::assertStringNotContainsString($secret, $serialized);
        }
    }

    public function testActualFrontendPostPersistsAuthoritativeSnapshotThenPreparesBothEmailMessages(): void
    {
        $fixture = $this->pipeline();
        $post = $this->payload();
        $post += ['store_id' => '99', 'customer_id' => '987', 'customer_group_id' => '8',
            'product_name' => 'Forged browser name', 'product_sku' => 'FORGED', 'product_url' => 'javascript:alert(1)',
            'request_status' => 'closed', 'email_status' => 'sent', 'email_attempts' => '100'];
        $response = $this->dispatch($fixture, $post, 'accepted');
        self::assertSame(['http_status' => 200, 'body' => ['success' => true, 'status' => 'accepted',
            'message' => 'Your quote request has been received.', 'request_id' => 1]], $response);
        $state = $fixture['state'];
        self::assertCount(1, $state->rows);
        $row = array_values($state->rows)[0];
        self::assertSame(2, $row['store_id']);
        self::assertNull($row['customer_id']);
        self::assertSame(42, $row['product_id']);
        self::assertSame('Authoritative server product', $row['product_name']);
        self::assertSame('SERVER42', $row['product_sku']);
        self::assertSame('https://shop.example.invalid/server-product.html', $row['product_url']);
        self::assertSame('2.5000', $row['quantity']);
        self::assertSame('new', $row['request_status']);
        self::assertSame('sent', $row['email_status']);
        self::assertSame(1, $row['email_attempts']);
        self::assertArrayNotHasKey('form_key', $row);
        self::assertArrayNotHasKey('request_token', $row);
        foreach (['admin', 'customer'] as $kind) {
            self::assertCount(1, $state->mail[$kind]);
            $mail = $state->mail[$kind][0];
            self::assertSame(['area' => 'frontend', 'store' => 2], $mail['options']);
            self::assertSame('general', $mail['sender']);
            self::assertSame(2, $mail['store_id']);
            self::assertSame('Authoritative server product', $mail['variables']['product_name']);
            self::assertSame('2.5000', $mail['variables']['quantity']);
            self::assertSame('42', $mail['variables']['product_id']);
            self::assertSame($post['message'], $mail['variables']['message']);
        }
        self::assertSame('quotes@example.invalid', $state->mail['admin'][0]['recipient']);
