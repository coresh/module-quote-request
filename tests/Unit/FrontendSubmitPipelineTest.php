    private function payload(string $id = 'modal_first'): array
    {
        $fixture = json_decode((string) file_get_contents(__DIR__ . '/../Fixtures/frontend-submit-payloads.json'), true, 32, JSON_THROW_ON_ERROR);
        self::assertSame(1, $fixture['schema_version']);
        self::assertSame('view/frontend/web/js/quote-request.js', $fixture['source']);
        self::assertSame(hash_file('sha256', dirname(__DIR__, 2) . '/' . $fixture['source']), $fixture['source_sha256'],
            'Captured payloads must belong to the current shipped AMD source.');
        foreach ($fixture['captures'] as $capture) {
            if ($capture['id'] === $id) {
                self::assertSame('POST', strtoupper($capture['ajax']['method']));
                self::assertSame('/quoterequest/request/submit', rtrim($capture['ajax']['url'], '/'));
                parse_str($capture['encoded_post'], $posted);
                $expected = $capture['post'];
                if (($expected['super_attribute'] ?? null) === []) {
                    unset($expected['super_attribute']); // URL form encoding omits empty option containers.
                }
                self::assertSame($expected, $posted, 'HTTP form decoding must match the encoded AJAX fields.');
                return $posted;
            }
        }
        self::fail('Missing actual AMD POST capture: ' . $id);
    }

